def glossary_for(text: str) -> list[tuple[str, str]]:
    """The glossary entries whose terms actually appear in this report.

    A glossary listing terms the reader never encountered is padding, and it
    buries the handful that matter. Only what was used is defined.
    """
    lowered = text.lower()
    aliases = {
        "macro F1": ("macro f1", "macro-f1", "f1_macro", "f1 macro"),
        "ROC AUC": ("roc auc", "roc_auc", "roc-auc", "auc"),
        "R-squared": ("r-squared", "r squared", "r2", "r\u00b2"),
        "eta-squared": ("eta-squared", "eta squared", "\u03b7\u00b2", "eta_squared"),
        "Cramer's V": ("cramer", "cram\u00e9r"),
        "principal components (PCA)": ("pca", "principal component"),
        "silhouette score": ("silhouette",),
        "permutation test": ("permutation",),
        "cross-validation": ("cross-valid", "cross valid"),
        "multicollinearity": ("multicollinear", "collinear"),
        "mutual information": ("mutual information",),
        "class imbalance": ("imbalance",),
        # Reports state the figure, not the term: "p=0.0196" is what appears,
        # so matching only the word "p-value" defined it for nobody.
        "p-value": ("p-value", "p_value", "p = ", "p="),
        "statistically significant": ("significant", "significance"),
        "feature engineering": ("feature engineering", "derived feature"),
    }
    found = []
    for term, definition in GLOSSARY.items():
        needles = aliases.get(term, (term.lower(),))
        if any(needle in lowered for needle in needles):
            found.append((term, definition))
    return found


# --------------------------------------------------------------------------- #
# What the model does, in counts
# --------------------------------------------------------------------------- #

def practical_behaviour(behaviour: dict | None, target: str | None) -> list[str]:
    """The model's behaviour as counts a reader can act on.

    A score is a number on a scale nobody has intuition for. "macro F1 0.7374"
    does not tell a clinician how many patients with the condition this finds,
    or how many healthy ones it wrongly flags -- and a decision turns entirely
    on those two, which trade off against each other and cannot be collapsed
    into one figure.

    So the counts are stated instead, out-of-sample, per class. They are
    frequently less flattering than the score: a model reported at 0.77
    accuracy on the Pima diabetes data finds 57 of every 100 patients who
    actually have diabetes. Both statements are true; only the second tells
    the reader what they are deciding about.

    Written here rather than by the model, for the same reason every other
    number is: a translation that can drift from what was computed is not a
    translation.
    """
    if not behaviour:
        return []

    subject = f"`{target}`" if target else "the outcome"
    out: list[str] = ["## What This Means in Practice\n"]

    if behaviour.get("kind") == "classification":
        out.append(
            f"The figures below come from predictions made on rows the model "
            f"had not seen, across all {behaviour.get('n_predictions', 0):,} "
            f"records. They describe what using it would actually look like.\n")
        for entry in behaviour.get("per_class", []):
            label = entry.get("class")
            actual = entry.get("actual_count") or 0
            found = entry.get("correctly_identified") or 0
            rate = entry.get("found_per_100")
            false_rate = entry.get("false_alarms_per_100_others")
            missed = actual - found

            sentence = (f"**When {subject} is `{label}`** ({actual:,} of the "
                        f"records): the model identifies {found:,} of them")
            if rate is not None:
                sentence += f" -- {rate:g} in every 100"
            sentence += "."
            if missed > 0:
                sentence += (f" The remaining {missed:,} are missed: the model "
                             f"labels them as something else.")
            if false_rate is not None and false_rate > 0:
                sentence += (f" It also wrongly assigns this label to "
                             f"{false_rate:g} in every 100 records that are "
                             f"not `{label}`.")
            out.append(sentence + "\n")

        out.append(
            "Whether that balance is acceptable depends on what each kind of "
            "mistake costs, which is a judgement about the situation rather "
            "than about the data. The analysis cannot make it, so it reports "
            "both numbers instead of choosing between them.\n")
        return out

    if behaviour.get("kind") == "regression":
        median = behaviour.get("median_absolute_error")
        p90 = behaviour.get("error_90th_percentile")
        spread = behaviour.get("central_spread_of_target")
        share = behaviour.get("error_as_share_of_spread")
        if median is None:
            return []

        out.append(
            f"The figures below come from predictions made on rows the model "
            f"had not seen, across all {behaviour.get('n_predictions', 0):,} "
            f"records.\n")
        sentence = (f"Half the predictions fall within **{median:,.4g}** of the "
                    f"true value of {subject}, and nine in ten fall within "
                    f"**{p90:,.4g}**.")
        if spread and share is not None:
            sentence += (f" For scale, the middle 90% of actual values span "
                         f"{spread:,.4g}, so the typical error is about "
                         f"{share:.1%} of that range.")
        out.append(sentence + "\n")
        out.append(
            "An error is only large or small relative to what is being "
            "predicted and to what the decision can tolerate, so the range is "
            "given alongside it rather than the error on its own.\n")
        return out

    return out
