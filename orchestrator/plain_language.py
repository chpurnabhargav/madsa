"""Translate computed statistics into sentences a non-specialist can act on.

The framework's reports were written for someone who already knows what a macro
F1 score, an eta-squared or a silhouette coefficient is -- which is to say, for
a data scientist reviewing automated work. That is a real audience, but it is
not usually the one a report is *for*. The person who has to decide something
is more often a clinician, an analyst, or a manager, and handing them
"eta-squared = 0.6031" transfers no understanding at all.

So every number the report states is accompanied by what it means. Not instead
of the number -- alongside it, because a reader who does know the statistic must
still be able to check it, and because removing the figure would make the report
unverifiable, which is the one thing this framework will not do.

Every translation here is derived from a computed value. None is generated by a
language model, and none says anything the measurement does not support. The
thresholds are the conventional ones (Cohen for effect sizes, the framework's
own permutation alpha for significance), and where a value sits near a boundary
the wording is deliberately cautious rather than decisive.
"""
from __future__ import annotations

from config import CONFIG

from typing import Any


# --------------------------------------------------------------------------- #
# Model performance
# --------------------------------------------------------------------------- #

def plain_score(metric: str, value: float | None, n_classes: int | None = None) -> str:
    """What a headline score means in practice.

    Accuracy is expressed as a rate out of a hundred because that is how people
    reason about it. Macro F1 is deliberately *not*, because it is an average of
    per-class balances and "97 out of 100" would be a misreading of it.
    """
    if value is None:
        return ""

    if metric == "accuracy":
        correct = round(value * 100)
        return (f"the model gets about {correct} out of every 100 cases right")

    if metric == "f1_macro":
        # Macro F1 weights every class equally, so a high value means the model
        # handles the rare classes too -- which is the property that matters and
        # the one plain accuracy hides.
        if value >= 0.9:
            quality = "very strong, and it handles the less common cases as well as the common ones"
        elif value >= 0.75:
            quality = "good, with reasonable handling of the less common cases"
        elif value >= 0.5:
            quality = "moderate; the less common cases are predicted noticeably worse"
        else:
            quality = "weak, particularly on the less common cases"
        return f"performance is {quality}"

    if metric == "roc_auc":
        chance = round(value * 100)
        return (f"given one positive and one negative case at random, the model "
                f"ranks them correctly about {chance}% of the time")

    if metric == "r2":
        share = round(value * 100)
        return (f"the model accounts for about {share}% of the variation in the "
                f"outcome; the rest is unexplained")

    return ""


def plain_baseline(lift: float | None, beats: bool | None) -> str:
    """Whether the model is doing better than guessing, in plain terms."""
    if beats is False:
        return ("This is no better than guessing. The data does not appear to "
                "contain a usable relationship with the outcome.")
    if lift is None:
        return ""
    return ("That is a clear improvement on guessing, which is the comparison "
            "that matters: a model can look accurate simply by always "
            "predicting the most common answer.")


def plain_significance(p_value: float | None, alpha: float | None = None) -> str:
    """What the permutation test establishes, without the word 'p-value'.

    The test shuffles the outcome column repeatedly and refits, measuring what
    score the model reaches when there is definitely nothing to learn. That is a
    far more intuitive thing to describe than a probability under a null
    hypothesis, and it is what the framework actually does.
    """
    # From config, not a literal. The threshold was written out here as 0.02
    # while `tools.modelling` reads `CONFIG.permutation_alpha` for the
    # `significant` flag, and neither caller passed one -- so changing the
    # setting would have made this sentence contradict the flag it describes,
    # in the same report.
    if alpha is None:
        alpha = CONFIG.permutation_alpha

    if p_value is None:
        return ""
    if p_value < alpha:
        return ("The result was tested by repeatedly shuffling the outcome column "
                "and refitting the model. The genuine result was better than "
                "almost every shuffled one, so the pattern is real rather than "
                "coincidence.")
    return ("The result was tested by repeatedly shuffling the outcome column "
            "and refitting the model. The genuine result was not clearly better "
            "than the shuffled ones, which means the apparent pattern could "
            "easily be coincidence.")


# --------------------------------------------------------------------------- #
# Effect sizes
# --------------------------------------------------------------------------- #

def plain_effect(kind: str, value: float | None) -> str:
    """How much a relationship actually matters, separate from whether it exists.

    Significance and importance are different questions, and on a large dataset
    almost everything is significant. Effect size answers the question people
    actually mean.
    """
    if value is None:
        return ""
    magnitude = abs(value)

    if kind in ("eta_squared", "r_squared"):
        share = round(magnitude * 100)
        strength = ("a large part of" if magnitude >= 0.14
                    else "a moderate part of" if magnitude >= 0.06
                    else "only a small part of")
        return (f"this accounts for {strength} the differences observed "
                f"(about {share}%)")

    if kind == "cramers_v":
        strength = ("strongly related" if magnitude >= 0.5
                    else "moderately related" if magnitude >= 0.3
                    else "weakly related" if magnitude >= 0.1
                    else "barely related")
        return f"the two are {strength}"

    if kind in ("pearson", "spearman", "correlation"):
        direction = "rise together" if value > 0 else "move in opposite directions"
        strength = ("very closely" if magnitude >= 0.8
                    else "closely" if magnitude >= 0.6
                    else "somewhat" if magnitude >= 0.3
                    else "barely")
        if magnitude >= 0.95:
            return ("these two measure almost the same thing -- keeping both "
                    "adds nothing")
        return f"they {direction}, {strength} so"

    return ""


def plain_silhouette(value: float | None) -> str:
    """Whether discovered groupings are real, which clustering never tells you.

    k-means returns clusters whatever the data looks like, so the number of
    clusters is not evidence that any exist.
    """
    if value is None:
        return ""
    if value >= 0.5:
        return ("The rows genuinely fall into separate groups; the division is "
                "clear rather than imposed.")
    if value >= 0.25:
        return ("There is some grouping structure, but the boundaries are soft "
                "and the groups overlap.")
    return ("The rows do not fall into natural groups. The grouping shown is an "
            "artefact of the method, which always returns groups whether or not "
            "any exist, and should not be treated as segments.")


