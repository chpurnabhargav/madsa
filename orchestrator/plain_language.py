VERDICT_MEANING = {
    "sound": (
        "The automated checks found nothing to correct. Every figure quoted was "
        "traced back to a calculation, and no claim in this report goes beyond "
        "what the analysis measured."),
    "needs_revision": (
        "The automated checks raised points worth a second look before this is "
        "relied upon. These are listed in full further down. They are not "
        "necessarily errors -- most often they are statements that go slightly "
        "further than the measurements support, or two sections describing the "
        "same thing differently."),
    "unreliable": (
        "The automated checks found a serious problem, and this report should "
        "not be relied upon until it is resolved. The specifics are listed "
        "further down."),
}


def plain_verdict(verdict: str | None, counts: dict[str, int] | None = None) -> str:
    """What the validation verdict means for someone deciding whether to trust it.

    "NEEDS REVISION" at the top of a document reads, to a non-specialist, as
    "this report is broken". It does not mean that: it means an automated
    reviewer flagged something for a human to confirm. Saying so is the
    difference between a reader who reads on and one who stops.
    """
    if not verdict:
        return ""
    base = VERDICT_MEANING.get(verdict, "")
    if counts and verdict != "sound":
        critical = counts.get("critical", 0)
        if critical:
            return base + f" {critical} of these is serious."
    return base


def plain_sample_size(n_rows: int, n_features: int) -> str:
    """Whether there is enough data to support the conclusions.

    Roughly ten rows per feature is the conventional minimum for stable
    estimates; below that, results move substantially between samples.
    """
    if n_rows < 50:
        return ("This dataset is very small. Conclusions drawn from it could "
                "change substantially with a few more rows, and should be "
                "treated as provisional.")
    ratio = n_rows / max(n_features, 1)
    if ratio < 10:
        return (f"There are {n_rows:,} rows for {n_features} measurements, which "
                f"is fewer than is usually comfortable. Findings may not hold on "
                f"a fresh sample.")
    if n_rows < 500:
        return (f"With {n_rows:,} rows this is a modest dataset: adequate for the "
                f"patterns reported, but a larger sample would firm them up.")
    return (f"With {n_rows:,} rows there is enough data for the patterns reported "
            f"to be reasonably stable.")


def plain_imbalance(ratio: float | None) -> str:
    """Why an uneven outcome split changes how scores should be read."""
    if ratio is None or ratio < 1.5:
        return ""
    if ratio >= 9:
        return (f"The outcome is heavily uneven ({ratio:.1f} to 1). A model that "
                f"simply always predicted the common answer would look accurate "
                f"while being useless, which is why accuracy alone is not "
                f"reported here.")
    return (f"The outcome is uneven ({ratio:.1f} to 1), so accuracy alone would "
            f"flatter the model; the balanced measures reported here account "
            f"for that.")


def chart_guidance(kind: str, chart: dict[str, Any]) -> str:
    """What to look for in a chart, rather than what it contains.

    A caption saying "bar chart of survival by class" tells a reader what they
    can already see. What they usually cannot see is which part of it carries
    the finding.

    The keys must be the chart kinds `tools.visualization.BUILDERS` actually
    produces. Two of them were not: "box_plot" where the builder is "box", and
    "feature_importance", which is not a chart this framework draws. Both
    returned the empty string, so box plots silently lost their note and nobody
    was told. A test now compares the two sets.
    """
    guidance = {
        "target_balance":
            "Look at how uneven the bars are. A very uneven split means accuracy "
            "is a misleading measure of success.",
        "grouped_rate":
            "Look at the gap between the tallest and shortest bar. The wider that "
            "gap, the more this factor matters to the outcome.",
        "box":
            "Compare where the boxes sit vertically. Boxes that barely overlap "
            "indicate a factor that genuinely separates the groups.",
        "bar":
            "Look at the relative heights, and at how many categories are tiny. "
            "A long tail of rare categories is often worth grouping together "
            "rather than treating each as its own case.",
        "heatmap":
            "Look for the darkest squares away from the diagonal. Those pairs "
            "measure nearly the same thing, so including both adds little.",
        "scatter":
            "Look at how tightly the points follow a line. Scattered points mean "
            "the relationship is weak even if a trend is drawn.",
        "histogram":
            "Look at whether the shape is lopsided. A long tail on one side means "
            "averages will be pulled towards the extreme values.",

    }
    return guidance.get(kind, "")


